"""canonicalize() must match the TypeScript SDK byte for byte.

js_canonical_vectors.json was generated by running JSON.stringify in Node on
the same inputs (see the "strsIn"/"numsIn" keys). If a bundle built here hashes
differently from the one the TS verifyBundle() recomputes, it fails with
root_mismatch, so these cases are the contract.
"""

import json
from pathlib import Path

from mnemopay.governance.audit_chain import AuditChain, canonicalize, verify_bundle

VECTORS = json.loads((Path(__file__).parent / "js_canonical_vectors.json").read_text(encoding="utf-8"))


def test_strings_match_json_stringify():
    for raw, expected in zip(VECTORS["strsIn"], VECTORS["strs"]):
        assert canonicalize(raw) == expected, repr(raw)


def test_numbers_match_json_stringify():
    for raw, expected in zip(VECTORS["numsIn"], VECTORS["nums"]):
        value = -0.0 if raw == "-0" else float(raw)
        assert canonicalize(value) == expected, raw


def test_integers_and_non_finite():
    assert canonicalize(7) == "7"
    assert canonicalize(-3) == "-3"
    assert canonicalize(2**70) == "1.1805916207174113e+21"
    assert canonicalize(float("nan")) == "null"
    assert canonicalize(float("inf")) == "null"


def test_object_keys_use_js_string_escaping():
    assert canonicalize({"é": 1, "a": "x"}) == '{"a":"x","é":1}'


def test_non_ascii_bundle_still_verifies_locally():
    chain = AuditChain()
    chain.emit("note", {"text": "café 😀   \x7f", "n": 1e21, "tiny": 1.5e-7})
    assert verify_bundle(chain.to_bundle()) == {"ok": True}
